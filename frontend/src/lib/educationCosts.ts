// 文部科学省「子供の学習費調査」(令和3年度) と
// 「私立大学等の令和4年度入学者に係る学生納付金等調査結果」を参考にした
// 子供 1 人あたりの年間教育費（円）。
// 値は概算・丸めあり。実支出を保証するものではないため、画面上は参考値として表記する。

export type EducationPath = 'public' | 'private' | 'mixed';

export const EDUCATION_PATH_LABELS: Record<EducationPath, string> = {
  public: 'すべて公立',
  private: 'すべて私立',
  mixed: '公立中心・大学私立',
};

interface CostTable {
  // age -> annual cost (円)
  [age: number]: number;
}

const PUBLIC: CostTable = {
  // 0-2 歳：保育園を想定（簡略化のため平均的な負担額）
  0: 120000, 1: 120000, 2: 120000,
  // 3-5 歳：幼稚園 公立 年間 約22万
  3: 220000, 4: 220000, 5: 220000,
  // 6-11 歳：小学校 公立 年間 約35万
  6: 350000, 7: 350000, 8: 350000, 9: 350000, 10: 350000, 11: 350000,
  // 12-14 歳：中学校 公立 年間 約54万
  12: 540000, 13: 540000, 14: 540000,
  // 15-17 歳：高校 公立 年間 約51万
  15: 510000, 16: 510000, 17: 510000,
  // 18-21 歳：大学 国公立 年間 約64万（入学金は初年度に按分）
  18: 720000, 19: 640000, 20: 640000, 21: 640000,
};

const PRIVATE: CostTable = {
  0: 120000, 1: 120000, 2: 120000,
  // 幼稚園 私立 年間 約53万
  3: 530000, 4: 530000, 5: 530000,
  // 小学校 私立 年間 約167万
  6: 1670000, 7: 1670000, 8: 1670000, 9: 1670000, 10: 1670000, 11: 1670000,
  // 中学校 私立 年間 約144万
  12: 1440000, 13: 1440000, 14: 1440000,
  // 高校 私立 年間 約105万
  15: 1050000, 16: 1050000, 17: 1050000,
  // 大学 私立文系 年間 約136万（初年度は入学金を加算）
  18: 1600000, 19: 1360000, 20: 1360000, 21: 1360000,
};

const MIXED: CostTable = {
  // 公立 K-12 + 大学のみ私立
  ...PUBLIC,
  18: 1600000, 19: 1360000, 20: 1360000, 21: 1360000,
};

const TABLES: Record<EducationPath, CostTable> = {
  public: PUBLIC,
  private: PRIVATE,
  mixed: MIXED,
};

/**
 * 子供 1 人の特定年齢における年間教育費（円）。
 * 22 歳以上は 0 として扱う。
 */
export function annualEducationCost(age: number, path: EducationPath): number {
  if (age < 0 || age > 21) return 0;
  return TABLES[path][age] ?? 0;
}
